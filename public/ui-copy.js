/** Format once: user values containing braces are never interpreted as templates or HTML. */
export function uiText(key, ...values) {
  if (!Object.hasOwn(UI_COPY, key)) throw new Error(`Unknown UI copy key: ${key}`);
  return UI_COPY[key].replace(/\{(\d+)\}/g, (_, index) => {
    if (Number(index) >= values.length) throw new Error(`Missing UI copy argument ${index}: ${key}`);
    return String(values[Number(index)]);
  });
}
